// Generate fallback translations for other languages preserving structural and key parity
const fallbackLangs = ['bn', 'ta', 'te', 'mr', 'ur', 'gu', 'kn', 'ml', 'pa', 'or', 'as']
for (const lang of fallbackLangs) {
  studentStrings[lang] = {}
  for (const [k, v] of Object.entries(studentStrings.en)) {
    studentStrings[lang][k] = v
  }
}

const localesDir = join(process.cwd(), 'src', 'i18n', 'locales')

for (const lang of locales) {
  const filePath = join(localesDir, lang, 'common.json')
  const raw = await readFile(filePath, 'utf8')
  const json = JSON.parse(raw)
  Object.assign(json, studentStrings[lang] || studentStrings.en)
  await writeFile(filePath, JSON.stringify(json, null, 2) + '\n', 'utf8')
  console.log(`Updated ${lang}/common.json`)
}

